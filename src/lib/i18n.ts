export function translate(value: string, language: Language): string {
  if (language === "uz") return value;
  return dictionaries[language][value] ?? value;
}

const textState = new WeakMap<Text, { original: string; last: string }>();
const attributeState = new WeakMap<Element, Map<string, { original: string; last: string }>>();

export function applyDomTranslations(root: HTMLElement, language: Language) {
  const textKeys = ["placeholder", "title", "aria-label", "alt"];

  const translateTextNode = (node: Text) => {
    const current = node.nodeValue ?? "";
    const previous = textState.get(node);
    const original = previous && current === previous.last ? previous.original : current;
    const trimmed = original.trim();
    if (!trimmed) return;
    const start = original.slice(0, original.indexOf(trimmed));
    const end = original.slice(original.indexOf(trimmed) + trimmed.length);
    const next = `${start}${translate(trimmed, language)}${end}`;
    if (next !== current) node.nodeValue = next;
    textState.set(node, { original, last: next });
  };

  const translateAttributes = (element: Element) => {
    const state = attributeState.get(element) ?? new Map<string, { original: string; last: string }>();
    for (const key of textKeys) {
      const current = element.getAttribute(key);
      if (current === null) continue;
      const previous = state.get(key);
      const original = previous && current === previous.last ? previous.original : current;
      const next = translate(original, language);
      if (next !== current) element.setAttribute(key, next);
      state.set(key, { original, last: next });
    }
    attributeState.set(element, state);
  };

  const walk = (node: Node) => {
    if (node.nodeType === Node.TEXT_NODE) {
      translateTextNode(node as Text);
      return;
    }
    if (node.nodeType === Node.ELEMENT_NODE) {
      translateAttributes(node as Element);
      for (const child of Array.from(node.childNodes)) walk(child);
    }
  };

  walk(root);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData" && record.target.nodeType === Node.TEXT_NODE) {
        translateTextNode(record.target as Text);
      } else {
        for (const node of Array.from(record.addedNodes)) walk(node);
        if (record.target.nodeType === Node.ELEMENT_NODE) translateAttributes(record.target as Element);
      }
    }
  });
  observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: textKeys });
  return () => observer.disconnect();
}
